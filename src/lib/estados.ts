export const slugify = (nombre: string) =>
  nombre
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

export const ESTADOS: Estado[] = raw.map(([code, nombre]) => ({
  code,
  nombre,
  slug: slugify(nombre),
}));

export const estadoPorSlug = (slug: string) => ESTADOS.find((e) => e.slug === slug);
export const estadoPorCode = (code: string) => ESTADOS.find((e) => e.code === code);
